// Natural Earth land (public domain) → a compact module for the plugin:
// rings of points quantized to 1/Q degree, delta-encoded, simplified with
// Douglas–Peucker. Usage: node land.mjs <in.geojson> <tolerance-deg> <minAreaDeg2> [out.ts]
import { readFileSync, writeFileSync } from 'node:fs';

const [, , input, tolArg, minAreaArg, out] = process.argv;
const tol = Number(tolArg), minArea = Number(minAreaArg);
const Q = 10;
const gj = JSON.parse(readFileSync(input, 'utf8'));

function dp(pts, eps) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-12;
    let best = -1, bi = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const d = Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
      if (d > best) { best = d; bi = i; }
    }
    if (best > eps) { keep[bi] = 1; stack.push([a, bi], [bi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const area = (r) => { let s = 0; for (let i = 0; i < r.length; i++) { const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length]; s += x1 * y2 - x2 * y1; } return Math.abs(s / 2); };

const rings = [];
for (const f of gj.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p of polys) for (const r of p) {
    if (area(r) < minArea) continue;
    // Split at the start so DP keeps both ends of a closed ring.
    const mid = Math.floor(r.length / 2);
    const s = [...dp(r.slice(0, mid + 1), tol), ...dp(r.slice(mid), tol).slice(1)];
    const q = [];
    for (const [x, y] of s) {
      const qx = Math.round(x * Q), qy = Math.round(y * Q);
      const last = q[q.length - 1];
      if (!last || last[0] !== qx || last[1] !== qy) q.push([qx, qy]);
    }
    if (q.length >= 4) rings.push(q);
  }
}
// Rings as strings of base-64-ish signed deltas would be smaller; plain delta arrays read fine and gzip well.
const enc = rings.map((r) => { const o = []; let px = 0, py = 0; for (const [x, y] of r) { o.push(x - px, y - py); px = x; py = y; } return o; });
const pts = rings.reduce((a, r) => a + r.length, 0);
const body = JSON.stringify(enc);
console.log(`${rings.length} rings, ${pts} points, ${body.length} bytes`);
if (out) writeFileSync(out, `// Generated by scripts/land.mjs from Natural Earth ${input.split('/').pop()} (public domain, naturalearthdata.com):\n// land polygons, simplified (${tol}°), in tenths of a degree, each ring delta-encoded as [dlon, dlat, ...].\n// eslint-disable-next-line\nexport const LAND: number[][] = ${body};\n`);
